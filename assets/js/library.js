function abbrOf(termTitle) {
  const hits = Object.keys(window.ABBRS).filter(k => termTitle.indexOf(window.ABBRS[k]) >= 0);
  return hits.length ? "（缩写 " + hits.join(" / ") + "）" : "";
}

